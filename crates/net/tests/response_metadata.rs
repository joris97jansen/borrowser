//! AI8 independently authored expectations over production response construction.
use addressing::{BrowserUrl, ResourceAddress, ResourceKind as Purpose};
use net::{
    DeclaredContentLength as Length, HttpHeaders, HttpStatus, HttpStatusClass as Class,
    NetworkResponseInfo, ResponseContentType as Type,
};

type MimeCase<'a> = (&'a [&'a [u8]], &'a str, Option<&'a str>);

fn address(purpose: Purpose) -> ResourceAddress {
    ResourceAddress::new(
        BrowserUrl::parse("https://request.invalid/original?q=1#source")
            .unwrap()
            .url,
        purpose,
    )
}

fn response(name: &str, values: &[&[u8]]) -> NetworkResponseInfo {
    let mut headers = HttpHeaders::new();
    for value in values {
        headers.append(name, value).unwrap();
    }
    NetworkResponseInfo::http(
        &address(Purpose::Document),
        "https://request.invalid/original?q=1#source".into(),
        Some("https://selected.invalid/final#selected".into()),
        HttpStatus::try_from(200).unwrap(),
        headers,
    )
    .unwrap()
}

#[test]
fn ai8_mime_selection_and_charset_follow_fetch_order() {
    // Expected essence/charset pairs are literal, not generated by a parser or
    // by selecting a first/last field. Each slice is an original occurrence.
    let cases: &[MimeCase<'_>] = &[
        (&[b"TEXT/HTML;"], "text/html", None),
        (&[b"text/css"], "text/css", None),
        (&[b"image/avif"], "image/avif", None),
        (&[b"text/css;charset=\"UTF-8\""], "text/css", Some("UTF-8")),
        (&[b"text/css;charset=A;charset=B"], "text/css", Some("A")),
        (&[b"text/css;charset=;charset=B"], "text/css", Some("B")),
        (&[b"text/css;charset=\"\";charset=B"], "text/css", Some("")),
        (
            &[b"text/css;charset=\"a\\\"b;c,d\""],
            "text/css",
            Some("a\"b;c,d"),
        ),
        (&[b"text/css;note=\"a,b;c\", image/png"], "image/png", None),
        (
            &[b"text/css;charset=\"unfinished"],
            "text/css",
            Some("unfinished"),
        ),
        (&[b"text/css;note=\"", b"image/png"], "text/css", None),
        (&[b"text/css;charset=A", b"text/css"], "text/css", Some("A")),
        (
            &[b"text/css;charset=A", b"text/css;charset=B"],
            "text/css",
            Some("B"),
        ),
        (
            &[
                b"text/css;charset=A",
                b"text/css;charset=B",
                b"broken",
                b"*/*",
            ],
            "text/css",
            Some("B"),
        ),
        (
            &[b"text/css;charset=A", b"text/css;charset=B", b"text/css"],
            "text/css",
            Some("A"),
        ),
        (
            &[b"text/css", b"text/css;charset=B", b"text/css"],
            "text/css",
            None,
        ),
        (
            &[b"text/css;charset=A", b"image/png", b"text/css"],
            "text/css",
            None,
        ),
        (
            &[b"text/css;charset=A", b"broken", b"*/*", b"text/css"],
            "text/css",
            Some("A"),
        ),
        (&[b"image/png, text/css"], "text/css", None),
        (&[b"image/png", b"text/css"], "text/css", None),
        (&[b"text/css", b"image/png"], "image/png", None),
        (&[b"text/*"], "text/*", None),
        (&[b"*/css"], "*/css", None),
        (
            &[b"application/x-ai8;charset=X-UNKNOWN"],
            "application/x-ai8",
            Some("X-UNKNOWN"),
        ),
        (&[b"text/css;charset =UTF-8"], "text/css", None),
        (&[b"text/css;charset=\"\xff\""], "text/css", Some("ÿ")),
        (
            &[b"text/css;charset=\"a\\", b"image/png"],
            "text/css",
            Some("a, image/png"),
        ),
        // An escaped quote at the end of one occurrence keeps the next comma
        // quoted, even though it comes from logical field combination.
        (
            &[b"text/css;note=\"end\\\"", b"image/png"],
            "text/css",
            None,
        ),
    ];
    for (values, essence, charset) in cases {
        let facts = response("Content-Type", values);
        let Type::Parsed(value) = facts.content_type() else {
            panic!("expected selected MIME for {values:?}");
        };
        assert_eq!(value.mime_type(), *essence, "{values:?}");
        assert_eq!(value.charset(), *charset, "{values:?}");
        assert_eq!(
            facts.headers().values("content-type").collect::<Vec<_>>(),
            *values
        );
    }
}

#[test]
fn ai8_missing_empty_and_unusable_mime_remain_distinct() {
    for (values, expected) in [
        (vec![], Type::Missing),
        (vec![b"".as_slice()], Type::Empty),
        (vec![b" \t".as_slice(), b""], Type::Empty),
        (vec![b"broken".as_slice()], Type::Unusable),
        (vec![b"text/".as_slice()], Type::Unusable),
        (vec![b",".as_slice()], Type::Unusable),
        (vec![b";charset=UTF-8".as_slice()], Type::Unusable),
        (vec![b"*/*".as_slice()], Type::Unusable),
        (vec![b"\xff".as_slice()], Type::Unusable),
        (vec![b"\xc2\xa0text/css\xc2\xa0".as_slice()], Type::Unusable),
    ] {
        assert_eq!(response("content-type", &values).content_type(), &expected);
    }
}

#[test]
fn ai8_length_compares_text_before_syntax_and_range() {
    let cases: &[(&[&[u8]], Length)] = &[
        (&[], Length::Missing),
        (&[b"0"], Length::Value(0)),
        (&[b"7"], Length::Value(7)),
        (&[b"007"], Length::Value(7)),
        (&[b"7", b"7"], Length::Value(7)),
        (&[b"7, 7"], Length::Value(7)),
        (&[b"007", b"007"], Length::Value(7)),
        (&[b"\t7 ,\t7\t"], Length::Value(7)),
        (&[b"7, 007"], Length::Conflicting),
        (&[b"7", b"007"], Length::Conflicting),
        (&[b"7, 8"], Length::Conflicting),
        (&[b""], Length::Unusable),
        (&[b"-7"], Length::Unusable),
        (&[b"+7"], Length::Unusable),
        (&[b"7x"], Length::Unusable),
        (&[b"\"7\""], Length::Unusable),
        (&[b"\"7,7\""], Length::Unusable),
        (&[b"bad", b"bad"], Length::Unusable),
        (&[b"bad, 7"], Length::Conflicting),
        (&[b"7,,7"], Length::Conflicting),
        (&[b"18446744073709551615"], Length::Value(u64::MAX)),
        (&[b"18446744073709551616"], Length::OutOfRange),
        (&[b"18446744073709551616", b"0"], Length::Conflicting),
        (&[b"18446744073709551616", b"bad"], Length::Conflicting),
        (&[b"\xff"], Length::Unusable),
    ];
    for (values, expected) in cases {
        let facts = response("CONTENT-LENGTH", values);
        assert_eq!(facts.declared_content_length(), *expected, "{values:?}");
        assert_eq!(
            facts.headers().values("content-length").collect::<Vec<_>>(),
            *values
        );
    }
}

#[test]
fn ai8_status_class_preserves_unknown_codes_and_http_meaning() {
    for (code, class, success, error) in [
        (199, Class::Informational, false, false),
        (299, Class::Successful, true, false),
        (399, Class::Redirection, false, false),
        (471, Class::ClientError, false, true),
        (599, Class::ServerError, false, true),
    ] {
        let status = HttpStatus::try_from(code).unwrap();
        assert_eq!(status.class(), class);
        assert_eq!(status.code(), code);
        assert_eq!(status.is_success(), success);
        assert_eq!(status.is_http_error(), error);
    }
}

#[test]
fn ai8_purpose_and_raw_facts_are_independent_of_mime_and_normalization() {
    for purpose in [
        Purpose::Document,
        Purpose::Hyperlink,
        Purpose::Stylesheet,
        Purpose::Image,
        Purpose::Font,
        Purpose::Media,
        Purpose::Unknown,
    ] {
        let request = net::FetchRequest::try_new(
            1,
            address(purpose),
            net::RequestMethod::Get,
            HttpHeaders::new(),
            None,
            None,
        )
        .unwrap();
        let mut headers = HttpHeaders::new();
        headers.append("content-type", b"image/png").unwrap();
        let facts = NetworkResponseInfo::http(
            request.address(),
            request.original_url().as_str().into(),
            None,
            HttpStatus::try_from(200).unwrap(),
            headers,
        )
        .unwrap();
        assert_eq!(facts.resource_kind(), purpose);
        assert_eq!(facts.original_url(), request.original_url());
        assert!(facts.response_url().is_none());
        if matches!(purpose, Purpose::Font | Purpose::Media | Purpose::Unknown) {
            for route in [
                core_types::ResourceKind::Html,
                core_types::ResourceKind::Css,
                core_types::ResourceKind::Image,
            ] {
                assert!(request.validate_route(route).is_err());
            }
        }
    }
    let a = response("content-type", &[b"TEXT/CSS"]);
    let b = response("content-type", &[b"text/css"]);
    assert_eq!(a.content_type(), b.content_type());
    assert_ne!(a, b, "raw declarations remain equality facts");
    let retained = a.clone();
    assert_eq!(a, retained);
    let local = ResourceAddress::new(
        BrowserUrl::parse("file:///tmp/local.css").unwrap().url,
        Purpose::Stylesheet,
    );
    let local_fact = |mime: &str| {
        NetworkResponseInfo::local_file(
            &local,
            local.url().as_str().into(),
            None,
            Some(mime.into()),
        )
        .unwrap()
    };
    let a = local_fact("TEXT/CSS");
    let b = local_fact("text/css");
    assert_eq!(a.content_type(), b.content_type());
    assert_ne!(a, b, "raw local MIME remains an equality fact");
    assert!(a.headers().is_empty());
    assert!(a.status().is_none());
    assert_eq!(a.declared_content_length(), Length::Missing);
    assert!(a.redirect_chain().is_empty());
    assert_eq!(
        local_fact("text/css, image/png").content_type(),
        &Type::Unusable
    );
}

#[test]
fn ai8_metadata_debug_has_independent_literals_and_nested_redaction() {
    let mut headers = HttpHeaders::new();
    headers
        .append(
            "content-type",
            b"application/PRIVATE;charset=PRIVATE_CHARSET",
        )
        .unwrap();
    headers.append("content-length", b"987654321").unwrap();
    let facts = NetworkResponseInfo::http(
        &address(Purpose::Document),
        "PRIVATE_ISSUED".into(),
        Some("https://PRIVATE_RESPONSE.invalid/PRIVATE".into()),
        HttpStatus::try_from(200).unwrap(),
        headers,
    )
    .unwrap();
    assert_eq!(
        format!("{:?}", facts.content_type()),
        r#"Parsed(ContentType { mime_type: "<redacted>", charset_present: true })"#
    );
    assert_eq!(
        format!("{:#?}", facts.content_type()),
        r#"Parsed(
    ContentType {
        mime_type: "<redacted>",
        charset_present: true,
    },
)"#
    );
    assert_eq!(
        format!("{:?}", facts.declared_content_length()),
        r#"Value("<redacted>")"#
    );
    assert_eq!(
        format!("{:#?}", facts.declared_content_length()),
        "Value(\n    \"<redacted>\",\n)"
    );
    let event = net::NetEvent::Start {
        request_id: 876543210,
        response: facts,
    };
    assert_eq!(
        format!("{:?}", Some(Ok::<_, ()>(&event))),
        r#"Some(Ok(Start { response: NetworkResponseInfo { original_url: "<redacted>", requested_url: "<redacted>", response_url: "parsed", status: Some(HttpStatus(200)), headers: [("<redacted>", "<redacted>"), ("<redacted>", "<redacted>")], redirect_chain: [], local_content_type_present: false, resource_kind: Document, content_type: Parsed(ContentType { mime_type: "<redacted>", charset_present: true }), declared_content_length: Value("<redacted>"), status_class: Some(Successful) }, .. }))"#
    );
    let (tx, rx) = std::sync::mpsc::channel();
    drop(rx);
    let failed = tx.send(event).unwrap_err();
    for output in [
        format!("{failed:?}"),
        format!("{failed:#?}"),
        format!("{:?}", Some(&failed)),
        format!("{:#?}", Some(&failed)),
    ] {
        for private in [
            "PRIVATE",
            "987654321",
            "876543210",
            "request.invalid",
            "selected.invalid",
        ] {
            assert!(!output.contains(private));
        }
        assert!(output.len() < 4096);
    }
}

#[test]
fn ai8_large_quoted_metadata_is_bounded_and_does_not_mutate_headers() {
    let mut headers = HttpHeaders::new();
    let mut first = b"text/css;charset=\"".to_vec();
    first.extend(vec![0xff; 7000]);
    headers.append("content-type", &first).unwrap();
    for _ in 0..7 {
        headers.append("content-type", &vec![0xff; 7000]).unwrap();
    }
    headers.append("x-private", b"PRIVATE").unwrap();
    let before = headers.clone();
    let facts = NetworkResponseInfo::http(
        &address(Purpose::Stylesheet),
        "PRIVATE".into(),
        None,
        HttpStatus::try_from(200).unwrap(),
        headers,
    )
    .unwrap();
    assert_eq!(facts.headers(), &before);
    let Type::Parsed(mime) = facts.content_type() else {
        panic!("recoverable quoted charset");
    };
    assert_eq!(mime.mime_type(), "text/css");
    assert!(mime.charset().unwrap().starts_with('ÿ'));
    assert!(mime.charset().unwrap().contains(", "));
    for output in [format!("{facts:?}"), format!("{facts:#?}")] {
        assert!(!output.contains("PRIVATE"));
        assert!(!output.contains('ÿ'));
        assert!(output.len() < 4096);
    }
}

#[test]
fn ai8_large_run_charset_survives_eight_thousand_later_candidates() {
    // Semantic regression only: this also passes the earlier copying loop.
    // The isolated mime_extraction_allocations target measures allocation work.
    let mut values = vec![vec![0xff; 8000]; 4];
    values[0][..13].copy_from_slice(b"a/a;charset=\"");
    values[3][7999] = b'"';
    values.extend((0..4).map(|_| b"a/a,".repeat(2000)));
    let borrowed: Vec<_> = values.iter().map(Vec::as_slice).collect();
    let facts = response("content-type", &borrowed);
    let accounted: usize = facts
        .headers()
        .iter()
        .map(|(name, value)| name.len() + value.len() + 4)
        .sum();
    assert_eq!(accounted, 64_128);
    assert_eq!(b"HTTP/1.1 200 OK\r\n".len() + accounted + 2, 64_147);
    let Type::Parsed(mime) = facts.content_type() else {
        panic!("selected MIME");
    };
    assert_eq!(mime.mime_type(), "a/a");
    let expected = [
        "ÿ".repeat(7987),
        "ÿ".repeat(8000),
        "ÿ".repeat(8000),
        "ÿ".repeat(7999),
    ]
    .join(", ");
    assert_eq!(expected.len(), 63_978);
    assert_eq!(mime.charset(), Some(expected.as_str()));
    assert_eq!(
        facts.headers().values("content-type").collect::<Vec<_>>(),
        borrowed
    );
    assert_eq!(facts, facts.clone());
}

#[test]
fn ai8_local_metadata_is_a_single_loader_fact_without_http_provenance() {
    let address = ResourceAddress::new(
        BrowserUrl::parse("file:///tmp/local.css#source")
            .unwrap()
            .url,
        Purpose::Stylesheet,
    );
    for (raw, category) in [
        (None, Type::Missing),
        (Some(""), Type::Empty),
        (Some("broken"), Type::Unusable),
        (Some("text/css, image/png"), Type::Unusable),
    ] {
        let facts = NetworkResponseInfo::local_file(
            &address,
            "file:///tmp/local.css#source".into(),
            Some("file:///tmp/local.css#source".into()),
            raw.map(str::to_owned),
        )
        .unwrap();
        assert_eq!(facts.content_type(), &category);
        assert!(facts.status().is_none());
        assert!(facts.headers().is_empty());
        assert_eq!(facts.declared_content_length(), Length::Missing);
        assert_eq!(facts.resource_kind(), Purpose::Stylesheet);
    }
}
